import { readFile, writeFile } from "node:fs/promises";
import { parseMethodSafetyCatalog } from "../src/method-safety.js";

const catalogUrl = new URL(
  "../../../docs/grokbot-tools-and-api.json",
  import.meta.url,
);
const tableUrl = new URL("../src/method-safety-table.ts", import.meta.url);

const catalog: unknown = JSON.parse(await readFile(catalogUrl, "utf8"));
const rows = parseMethodSafetyCatalog(catalog)
  .map(([name, safety]) => `  ${name}: ${JSON.stringify(safety)},`)
  .join("\n");

await writeFile(
  tableUrl,
  `// Generated by scripts/generate-method-safety-table.ts from docs/grokbot-tools-and-api.json. Do not edit.
import type { MethodSafety } from "./method-safety.js";

export const SERVER_METHOD_SAFETY = {
${rows}
} as const satisfies Readonly<Record<string, MethodSafety>>;
`,
);
